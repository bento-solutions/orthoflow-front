/**
 * The states of the "Référentiel des états cliniques dentaires" that the base lexicon
 * (clinical-lexicon.ts) did not already name. One definition per state, with the words a
 * dentist says for it in French and English, and its name in Arabic.
 *
 * Order is significance, exactly as in clinical-lexicon.ts: a definition earlier in the list
 * claims its words before a later one can. Everything here that is more specific than a
 * legacy word ("fracture radiculaire" against "fracture", "couronne sur implant" against
 * "couronne" and "implant") is therefore in {@link REFERENTIAL_FIRST}, tried before the whole
 * legacy list; tartar and plaque, which the legacy "plaque / tartre" phrase must claim first,
 * are in {@link REFERENTIAL_AFTER}.
 *
 * The codes must match the server's FindingCatalog.java, state for state. The Arabic patterns
 * are the Arabic names on the chart, with the definite article optional on each word, so an
 * Arabic dictation reads the same states.
 */

